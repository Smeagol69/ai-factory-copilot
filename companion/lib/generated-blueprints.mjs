/**
 * Compile an existing deterministic placement plan into one native Blueprint
 * generation request.
 *
 * This is deliberately a geometry adapter, not a second factory planner. The
 * production and architecture solvers remain responsible for recipe choice,
 * counts and positions. This module changes only the coordinate space: exact
 * world transforms become exact Blueprint-relative transforms, while every
 * recipe identity survives unchanged for the game to revalidate.
 */

function finite(value) {
  const number = Number(value);
  return Number.isFinite(number) ? number : null;
}

function explicitVector(value) {
  if (!value || typeof value !== "object") return null;
  const x = finite(value.x);
  const y = finite(value.y);
  const z = finite(value.z);
  return x === null || y === null || z === null ? null : { x, y, z };
}

function cleanBlueprintName(value) {
  const name = String(value ?? "").replace(/[\r\n\t]/g, " ").replace(/\s+/g, " ").trim();
  return name && name.length <= 240 ? name : null;
}

/**
 * @param {object} args
 * @param {string} args.blueprint_name Native library name.
 * @param {Array<object>} args.actions Existing exact placement proposals.
 * @param {object=} args.origin_cm Explicit reference point. When absent, the
 * first building is the origin; no minimum-bounds guess changes the layout.
 * @param {string=} args.description Native Blueprint description.
 * @param {string=} args.schema v1 preserves the standalone-only contract; v2
 * carries explicit native conveyor and physical power-wire topology.
 * @param {Array<object>=} args.power_connections Explicit wire links expressed
 * with from_step/to_step references to place_building actions.
 */
export function compileGeneratedBlueprint({
  blueprint_name: blueprintName,
  actions,
  origin_cm: originOverride = null,
  description = "AI-designed native Blueprint generated by AI Factory Copilot.",
  schema = "aifactory.generated-blueprint/v2",
  power_connections: powerConnections = [],
} = {}) {
  const name = cleanBlueprintName(blueprintName);
  if (!name) {
    return { compiled: false, reason: "blueprint_name_must_be_1_to_240_printable_characters" };
  }
  if (!Array.isArray(actions) || actions.length === 0) {
    return { compiled: false, reason: "a_generated_blueprint_needs_at_least_one_building" };
  }

  if (!["aifactory.generated-blueprint/v1", "aifactory.generated-blueprint/v2"].includes(schema)) {
    return { compiled: false, reason: "unsupported_generated_blueprint_schema" };
  }

  const supportedActions = schema === "aifactory.generated-blueprint/v1"
    ? new Set(["place_building"])
    : new Set(["place_building", "place_belt"]);
  const unsupported = actions
    .map((action, index) => ({ action, index }))
    .filter(({ action }) => !supportedActions.has(action?.action))
    .map(({ action, index }) => ({ step: index + 1, action: action?.action ?? null }));
  if (unsupported.length > 0) {
    return {
      compiled: false,
      reason: schema.endsWith("/v1")
        ? "generated_blueprint_v1_accepts_only_standalone_buildings"
        : "generated_blueprint_v2_action_is_unsupported",
      unsupported,
      unsupported_note:
        "Belts, pipes, wires, miners/resource anchors and attachment-dependent pieces need native topology-specific generation before they may be included.",
    };
  }

  const buildingActions = actions.filter((action) => action?.action === "place_building");
  if (buildingActions.length === 0) {
    return { compiled: false, reason: "a_generated_blueprint_needs_at_least_one_building" };
  }
  const locations = buildingActions.map((action) => explicitVector(action?.location));
  const inferredOrigin = locations.every(Boolean)
    ? {
        x: Math.min(...locations.map((location) => location.x)),
        y: Math.min(...locations.map((location) => location.y)),
        z: Math.min(...locations.map((location) => location.z)),
      }
    : null;
  const origin = explicitVector(originOverride) ?? inferredOrigin;
  if (!origin) {
    return { compiled: false, reason: "generated_blueprint_origin_is_not_finite_xyz" };
  }

  const buildables = [];
  const partIdByActionStep = new Map();
  for (const [index, action] of actions.entries()) {
    if (action?.action !== "place_building") continue;
    const recipeClass = String(action?.recipe_class ?? "").trim();
    const location = explicitVector(action?.location);
    const yaw = finite(action?.yaw ?? 0);
    if (!recipeClass) {
      return { compiled: false, reason: "generated_building_recipe_is_required", step: index + 1 };
    }
    if (!location || yaw === null) {
      return { compiled: false, reason: "generated_building_transform_must_be_finite", step: index + 1 };
    }
    if (action.target_actor_id || action.target_step) {
      return {
        compiled: false,
        reason: "generated_blueprint_v1_does_not_support_snap_or_resource_targets",
        step: index + 1,
      };
    }

    const partId = `part-${String(index + 1).padStart(4, "0")}`;
    partIdByActionStep.set(index + 1, partId);
    buildables.push({
      part_id: partId,
      role: String(action.generated_role ?? "standalone").trim().toLowerCase(),
      recipe_class: recipeClass,
      ...(String(action.production_recipe_class ?? "").trim()
        ? { production_recipe_class: String(action.production_recipe_class).trim() }
        : {}),
      relative_location: {
        x: location.x - origin.x,
        y: location.y - origin.y,
        z: location.z - origin.z,
      },
      yaw,
    });
  }

  const compileTopologyLinks = (links, kind) => {
    const compiled = [];
    const seen = new Set();
    for (const [index, link] of links.entries()) {
      const recipeClass = String(link?.recipe_class ?? "").trim();
      const fromStep = Number(link?.from_step);
      const toStep = Number(link?.to_step);
      const fromPartId = partIdByActionStep.get(fromStep);
      const toPartId = partIdByActionStep.get(toStep);
      if (!recipeClass) {
        return { ok: false, reason: `generated_${kind}_recipe_is_required`, link: index + 1 };
      }
      if (!Number.isInteger(fromStep) || !Number.isInteger(toStep) ||
          !fromPartId || !toPartId || fromPartId === toPartId) {
        return {
          ok: false,
          reason: `generated_${kind}_steps_must_reference_two_building_actions`,
          link: index + 1,
          from_step: link?.from_step ?? null,
          to_step: link?.to_step ?? null,
        };
      }
      if (link.from_component || link.to_component || link.from_actor_id || link.to_actor_id) {
        return {
          ok: false,
          reason: `generated_${kind}_must_use_blueprint_part_steps_not_live_world_ids`,
          link: index + 1,
        };
      }
      const linkId = `${kind}-${String(index + 1).padStart(4, "0")}`;
      const edgeKey = kind === "power_wire"
        ? [fromPartId, toPartId].sort().join("|")
        : `${fromPartId}|${toPartId}`;
      if (seen.has(edgeKey)) {
        return { ok: false, reason: `generated_${kind}_edge_is_duplicated`, link: index + 1 };
      }
      seen.add(edgeKey);
      compiled.push({
        link_id: linkId,
        recipe_class: recipeClass,
        from_part_id: fromPartId,
        to_part_id: toPartId,
        ...(String(link?.from_connector_name ?? "").trim()
          ? { from_connector_name: String(link.from_connector_name).trim() }
          : {}),
        ...(String(link?.to_connector_name ?? "").trim()
          ? { to_connector_name: String(link.to_connector_name).trim() }
          : {}),
      });
    }
    return { ok: true, links: compiled };
  };

  const beltActions = actions.filter((action) => action?.action === "place_belt");
  const compiledConveyors = compileTopologyLinks(beltActions, "conveyor");
  if (!compiledConveyors.ok) return { compiled: false, ...compiledConveyors };
  if (!Array.isArray(powerConnections)) {
    return { compiled: false, reason: "power_connections_must_be_an_array" };
  }
  const compiledPower = compileTopologyLinks(powerConnections, "power_wire");
  if (!compiledPower.ok) return { compiled: false, ...compiledPower };
  if (schema.endsWith("/v1") && compiledPower.links.length > 0) {
    return { compiled: false, reason: "generated_blueprint_v1_accepts_only_standalone_buildings" };
  }

  return {
    compiled: true,
    schema,
    blueprint_name: name,
    description: String(description ?? "").trim().slice(0, 1_000),
    origin_cm: origin,
    buildables,
    conveyors: compiledConveyors.links,
    power_wires: compiledPower.links,
    counts: {
      buildables: buildables.length,
      configured_manufacturers: buildables.filter((part) => part.production_recipe_class).length,
      conveyors: compiledConveyors.links.length,
      power_wires: compiledPower.links.length,
    },
    topology: {
      belts: schema.endsWith("/v2")
        ? `${compiledConveyors.links.length}_explicit_native_links`
        : "not_generated_in_v1",
      pipes: schema.endsWith("/v2") ? "not_generated_in_v2" : "not_generated_in_v1",
      power_wires: schema.endsWith("/v2")
        ? `${compiledPower.links.length}_explicit_physical_links`
        : "not_generated_in_v1",
      miners_and_resource_anchors: schema.endsWith("/v2")
        ? "not_generated_in_v2"
        : "not_generated_in_v1",
    },
    validation:
      "The companion validates captured unlock evidence and finite relative geometry. The game resolves every class again, measures staged native component bounds, rejects internal volumetric overlap, serializes through a real Blueprint Designer, destroys all staging actors, and reads the file back.",
  };
}

/** Turn a compiled layout into the single typed write the game understands. */
export function generatedBlueprintAction(compiled, { commit = false } = {}) {
  if (!compiled?.compiled ||
      !["aifactory.generated-blueprint/v1", "aifactory.generated-blueprint/v2"].includes(compiled.schema)) {
    return null;
  }
  return {
    action: "generate_native_blueprint",
    blueprint_name: compiled.blueprint_name,
    description: compiled.description,
    layout_schema: compiled.schema,
    buildables: compiled.buildables,
    ...(compiled.schema.endsWith("/v2")
      ? { conveyors: compiled.conveyors ?? [], power_wires: compiled.power_wires ?? [] }
      : {}),
    commit: commit === true,
  };
}
