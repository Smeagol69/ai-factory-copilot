#!/usr/bin/env node
// Exports the Satisfactory part of the Agent Pair ledger - the shared record in
// which Claude and Codex coordinated this project (claims, handoffs, reviews,
// findings, shared memory) - into docs/history/ledger/, so the repo alone
// tells the whole story. One folder per ledger project. Run (read-only on the database):
//   node scripts/export-ledger.mjs [--db <pair.sqlite>]
// Default database: the Agent Pair coordinator's, in the Codex Store package
// (%LOCALAPPDATA%\Packages\OpenAI.Codex_2p2nqsd0c76g0\LocalCache\Local\AgentPair\pair.sqlite).
// Claim tokens are never exported; the owner's home folder becomes
// %USERPROFILE% and e-mail addresses are masked.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { DatabaseSync } from "node:sqlite";

const REPO = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(REPO, "docs", "history", "ledger");
const PROJECTS = ["satisfactory-mcp-lab", "satisfactory-ai-architect"];
const DEFAULT_DB = path.join(process.env.LOCALAPPDATA || "", "Packages", "OpenAI.Codex_2p2nqsd0c76g0", "LocalCache", "Local", "AgentPair", "pair.sqlite");

export function scrub(s) {
  return String(s ?? "")
    .replace(/[A-Za-z]:[\\/]+Users[\\/]+[^\\/\s"'`]+/gi, "%USERPROFILE%")
    .replace(/[A-Za-z0-9._%+-]+@(?!example\.)[A-Za-z0-9.-]+\.[a-z]{2,}/gi, (m) => (/noreply@anthropic\.com/i.test(m) ? m : "<email>"));
}
const iso = (ms) => (ms ? new Date(ms).toISOString().replace(".000Z", "Z") : "");
const day = (ms) => iso(ms).slice(0, 10);
const fence = (s) => {
  const text = scrub(s).replace(/\r\n/g, "\n").trimEnd();
  const ticks = (text.match(/`{3,}/g) || []).reduce((n, t) => Math.max(n, t.length + 1), 3);
  return `${"`".repeat(ticks)}text\n${text}\n${"`".repeat(ticks)}`;
};

export function exportLedger(dbPath = DEFAULT_DB, out = OUT, PROJECT = PROJECTS[0]) {
  const db = new DatabaseSync(dbPath, { readOnly: true });
  const all = (sql, ...a) => db.prepare(sql).all(...a);
  fs.rmSync(out, { recursive: true, force: true });
  fs.mkdirSync(out, { recursive: true });

  // Messages, one file per day.
  const msgs = all("SELECT id, sender, recipient, subject, body, reply_to, channel, created_at FROM messages WHERE project = ? ORDER BY id", PROJECT);
  const byDay = new Map();
  for (const m of msgs) {
    const d = day(m.created_at);
    if (!byDay.has(d)) byDay.set(d, []);
    byDay.get(d).push(m);
  }
  const index = [];
  for (const [d, list] of byDay) {
    const lines = [`# Ledger messages ${d}`, "", `${list.length} messages, project \`${PROJECT}\`. Generated by scripts/export-ledger.mjs.`, ""];
    for (const m of list) {
      lines.push(`## #${m.id} ${scrub(m.subject)}`, "", `- from **${m.sender}**${m.recipient ? ` to ${m.recipient}` : ""}, ${iso(m.created_at)}${m.reply_to ? `, reply to #${m.reply_to}` : ""}${m.channel && m.channel !== "work" ? `, channel ${m.channel}` : ""}`, "", fence(m.body), "");
      index.push(`| ${m.id} | ${d} | ${m.sender} | [${scrub(m.subject).replace(/\|/g, "\\|")}](messages-${d}.md#${m.id}-${slug(scrub(m.subject))}) |`);
    }
    fs.writeFileSync(path.join(out, `messages-${d}.md`), lines.join("\n") + "\n");
  }

  // Tasks (claims) with their handoff history. Never the claim token.
  // (tasks has no timestamp of its own: its first event dates it)
  const tasks = all("SELECT t.id, t.owner, t.status, t.branch, t.workspace, t.scopes, t.description, (SELECT min(e.created_at) FROM task_events e WHERE e.project = t.project AND e.task = t.id) AS created_at FROM tasks t WHERE t.project = ? ORDER BY created_at, t.id", PROJECT);
  const events = all("SELECT task, owner, status, handoff, created_at FROM task_events WHERE project = ? ORDER BY id", PROJECT);
  const tl = ["# Ledger tasks (claims and handoffs)", "", `${tasks.length} tasks, project \`${PROJECT}\`, oldest first. Each claim lists the files it covered and every status change with its handoff. Generated by scripts/export-ledger.mjs.`, ""];
  for (const t of tasks) {
    let scopes = t.scopes;
    try { scopes = JSON.parse(t.scopes).join(", "); } catch { /* as stored */ }
    tl.push(`## ${t.id}`, "", `- owner **${t.owner}**, status **${t.status}**, branch \`${t.branch || "-"}\`, claimed ${iso(t.created_at)}`, `- scopes: ${scrub(scopes)}`, "", scrub(t.description).replace(/\r\n/g, "\n"), "");
    for (const e of events.filter((x) => x.task === t.id && x.handoff)) tl.push(`### ${e.status} - ${iso(e.created_at)} (${e.owner})`, "", fence(e.handoff), "");
  }
  fs.writeFileSync(path.join(out, "tasks.md"), tl.join("\n") + "\n");

  // Shared memory, backlog, charter.
  const mem = all("SELECT kind, memory_key, content, evidence, tags, sender, created_at FROM office_memory_entries WHERE project = ? ORDER BY id", PROJECT);
  const backlog = all("SELECT * FROM backlog WHERE project = ? ORDER BY id", PROJECT);
  const charter = all("SELECT version, hash, text, created_at FROM charter_revisions WHERE project = ? ORDER BY created_at", PROJECT);
  const ml = ["# Ledger shared memory, backlog and charter", "", "Generated by scripts/export-ledger.mjs.", "", "## Shared memory (pair_remember / pair_update_summary)", ""];
  for (const m of mem) ml.push(`### ${m.kind}${m.memory_key ? ` \`${m.memory_key}\`` : ""} - ${m.sender}, ${iso(m.created_at)}`, "", fence(m.content), m.evidence ? `Evidence: ${scrub(m.evidence)}` : "", "");
  ml.push("## Backlog", "");
  for (const b of backlog) ml.push(`- #${b.id} **${scrub(b.title)}** (${b.status ?? "?"}, priority ${b.priority ?? "-"}): ${scrub(b.description).replace(/\r?\n/g, " ")}`);
  ml.push("", "## Charter revisions", "");
  for (const c of charter) ml.push(`### Version ${c.version} (${iso(c.created_at)}, sha256 ${c.hash.slice(0, 12)})`, "", fence(c.text), "");
  fs.writeFileSync(path.join(out, "memory-backlog-charter.md"), ml.join("\n") + "\n");

  const readme = [
    "# The Claude + Codex ledger for this project",
    "",
    `Claude and Codex worked on this repo through the Agent Pair coordinator (a separate project in \`Documents\\agent-pair-platform\` on the owner's PC): claims before editing, handoffs, review requests and verdicts, findings, shared memory. This folder is the full export of the \`${PROJECT}\` project from its database, so nothing that lived only there is missing from the repo.`,
    "",
    `Exported ${iso(Date.now())} by \`scripts/export-ledger.mjs\`: ${msgs.length} messages (${day(msgs[0]?.created_at)} to ${day(msgs.at(-1)?.created_at)}), ${tasks.length} tasks, ${mem.length} shared memory entries, ${backlog.length} backlog items, ${charter.length} charter revisions.`,
    "",
    "- [tasks.md](tasks.md) - every claim with its files, branch and handoffs",
    "- [memory-backlog-charter.md](memory-backlog-charter.md) - shared memory, backlog, the coordination charter",
    "- messages, one file per day (index below)",
    "",
    "Agents: `claude-<n>` are Claude Code sessions, `codex-<n>` Codex sessions; the number is the session's process id, so one agent appears under many ids. Commit hashes quoted in messages resolve in this repo: every branch either is in `master`'s history or is kept as a tag under `archive/` (see docs/HISTORY.md).",
    "",
    "| # | day | from | subject |",
    "|---|---|---|---|",
    ...index,
    "",
  ];
  fs.writeFileSync(path.join(out, "README.md"), readme.join("\n"));
  db.close();
  return { messages: msgs.length, tasks: tasks.length, memory: mem.length, days: byDay.size };
}

function slug(s) {
  return String(s).toLowerCase().replace(/[^\w\s-]/g, "").trim().replace(/\s+/g, "-");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const i = process.argv.indexOf("--db");
  for (const project of PROJECTS) {
    const out = path.join(OUT, project);
    const r = exportLedger(i > 0 ? process.argv[i + 1] : DEFAULT_DB, out, project);
    console.log(`Exported ${project}: ${r.messages} messages over ${r.days} days, ${r.tasks} tasks, ${r.memory} memory entries to ${out}`);
  }
}
